export function checkAnswerCorrectness(question: QuestionItem, rawInput: string): boolean {
  if (!rawInput) return false;
  const cleaned = rawInput.trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()]/g, '');

  if (question.type === 'true_false_not_given') {
    const norm = cleaned.toUpperCase();
    if (question.officialAnswer === 'TRUE') {
      return norm === 'TRUE' || norm === 'T';
    } else if (question.officialAnswer === 'FALSE') {
      return norm === 'FALSE' || norm === 'F';
    } else if (question.officialAnswer === 'NOT GIVEN') {
      return norm === 'NOT GIVEN' || norm === 'NOTGIVEN' || norm === 'NG';
    }
  }

  // Short answer / Flow chart completion checks
  const userTokens = cleaned.split(/\s+/).filter(Boolean).join(' ');
  for (const accepted of question.acceptedAnswers) {
    const accTokens = accepted.trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()]/g, '').split(/\s+/).filter(Boolean).join(' ');
    if (userTokens === accTokens) return true;
  }

  // Special checks for question 1 (unfit)
  if (question.id === 1) {
    if (['unfit', 'declared unfit', 'being unfit'].includes(userTokens)) {
      return true;
    }
  }

  // Special checks for question 2 (schools / school)
  if (question.id === 2) {
    if (['schools', 'school', 'in schools'].includes(userTokens)) {
      return true;
    }
  }

  // Special checks for question 3 (PE teachers)
  if (question.id === 3) {
    if (['pe teachers', 'pe teacher', 'physical education teachers', 'physical education teacher'].includes(userTokens)) {
      return true;
    }
  }

  // Special checks for question 4 (surplus)
  if (question.id === 4) {
    if (['surplus', 'the surplus', 'a surplus', 'surpluses'].includes(userTokens)) {
      return true;
    }
  }

  // Special checks for question 5 (employment opportunities / careers / routes)
  if (question.id === 5) {
    if (['employment opportunities', 'employment opportunity', 'careers', 'career opportunities', 'routes', 'employment', 'career paths', 'jobs'].includes(userTokens)) {
      return true;
    }
  }

  return false;
}

